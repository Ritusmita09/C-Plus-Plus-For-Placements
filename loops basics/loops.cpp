using namespace std;

int main(){
    for(int i=0; i<=8; i++){  //forward loop = [i= i+1/i++]
        cout<<"Ritusmita\n " << i <<"\n";
    }
    for(int j = 10; j >= 0; j--){ // backward loop = [j=j-1/j--]
        cout<<"C++ is cool\n " << j <<"\n";
    }
    for(int k = 1; k <= 20; k=k+5){
        cout<<"i can do whatever i want\n" << k <<"\n";
    }
}